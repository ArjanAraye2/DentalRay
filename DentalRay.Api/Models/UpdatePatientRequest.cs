using System;
using System.ComponentModel.DataAnnotations;

namespace DentalRay.Api.Models
{
    // ============================================================
    // UpdatePatientRequest
    // ============================================================
    //
    // این کلاس اطلاعاتی را مشخص می‌کند که Client اجازه دارد
    // هنگام ویرایش اطلاعات یک بیمار ارسال کند.
    //
    // چرا مستقیماً از Patient استفاده نمی‌کنیم؟
    //
    // چون بعضی فیلدهای Patient سیستمی هستند و Client نباید
    // بتواند آنها را آزادانه تغییر دهد، مانند:
    //
    // PatientID
    // CreatedDate
    // ModifiedDate
    // IsActive
    //
    // استفاده از Request Model یا DTO باعث می‌شود دقیقاً مشخص
    // کنیم چه اطلاعاتی اجازه ورود به API را دارند.
    // ============================================================

    public class UpdatePatientRequest
    {
        // --------------------------------------------------------
        // NationalCode
        // --------------------------------------------------------
        //
        // شناسه یکتای بیمار است.
        //
        // امکان اصلاح آن وجود دارد، اما API بررسی می‌کند که
        // NationalCode جدید قبلاً متعلق به بیمار دیگری نباشد.
        [Required]
        [MaxLength(20)]
        public string NationalCode { get; set; } = string.Empty;


        // --------------------------------------------------------
        // FirstName
        // --------------------------------------------------------

        [Required]
        [MaxLength(100)]
        public string FirstName { get; set; } = string.Empty;


        // --------------------------------------------------------
        // LastName
        // --------------------------------------------------------

        [Required]
        [MaxLength(100)]
        public string LastName { get; set; } = string.Empty;


        // --------------------------------------------------------
        // BirthDate
        // --------------------------------------------------------
        //
        // تاریخ در Backend و SQL Server به صورت استاندارد ذخیره
        // می‌شود.
        //
        // تبدیل و نمایش شمسی بعداً در Frontend انجام خواهد شد.
        public DateTime? BirthDate { get; set; }


        // --------------------------------------------------------
        // Gender
        // --------------------------------------------------------

        public byte? Gender { get; set; }


        // --------------------------------------------------------
        // Mobile
        // --------------------------------------------------------

        [MaxLength(30)]
        public string? Mobile { get; set; }


        // --------------------------------------------------------
        // Address
        // --------------------------------------------------------

        [MaxLength(500)]
        public string? Address { get; set; }


        // --------------------------------------------------------
        // Description
        // --------------------------------------------------------

        [MaxLength(1000)]
        public string? Description { get; set; }
    }
}